import logging
from pathlib import Path

import torch

from sfno.config import Config
from sfno.forcing import compute_xi_grid, generate_random_ic
from sfno.runtime import (
    capture_rng,
    load_torch,
    prepare_output,
    save_torch,
    seed_everything,
    sha256,
    write_json,
    write_manifest,
)
from sfno.solver import solve_stochastic_burgers_mc

LOGGER = logging.getLogger(__name__)


def build_dataset(num_samples, length_scale, config, device):
    physics, data = config.physics, config.data
    x_grid = torch.linspace(0, physics.length, data.nx, device=device)
    t_grid = torch.linspace(0, physics.duration, data.nt, device=device)
    parts = {key: [] for key in ("u0", "xi", "target", "coefficients")}
    with torch.no_grad():
        for start in range(0, num_samples, data.generation_batch_size):
            count = min(data.generation_batch_size, num_samples - start)
            coefficients = torch.randn(
                count, physics.forcing_modes_x * physics.forcing_modes_t, device=device
            )
            initial = generate_random_ic(count, x_grid, length_scale, physics)
            forcing = compute_xi_grid(coefficients, x_grid, t_grid, physics)
            target = solve_stochastic_burgers_mc(initial, coefficients, x_grid, t_grid, physics)
            for key, tensor in zip(parts, (initial, forcing, target, coefficients)):
                parts[key].append(tensor.cpu())
            LOGGER.info(
                "Generated %s/%s trajectories at length scale %s",
                start + count,
                num_samples,
                length_scale,
            )
    result = {key: torch.cat(value) for key, value in parts.items()}
    result.update({"x": x_grid.cpu(), "t": t_grid.cpu()})
    return result


def generate_datasets(config, device, output):
    config.validate()
    output = prepare_output(output)
    seed_everything(config.seed)
    train = build_dataset(config.data.train_samples, config.data.train_length_scale, config, device)
    test = build_dataset(config.data.test_samples, config.data.test_length_scale, config, device)
    payload = {
        "schema_version": 1,
        "kind": "sfno_dataset",
        "config": config.to_dict(),
        "config_sha256": config.fingerprint(),
        "device": str(device),
        "train": train,
        "test": test,
        "rng_after_data": capture_rng(),
    }
    path = output / "dataset.pt"
    save_torch(path, payload)
    write_json(output / "config.json", config.to_dict())
    write_manifest(output, "generate", config, device, [], [path, output / "config.json"])
    return path


def load_dataset(path, config=None):
    payload = load_torch(path)
    if payload.get("kind") != "sfno_dataset":
        raise ValueError("Expected a dataset generated by sfno generate.")
    stored_config = Config.from_dict(payload["config"])
    if payload["config_sha256"] != stored_config.fingerprint():
        raise ValueError("The saved dataset configuration fingerprint is invalid.")
    if config is not None and config.fingerprint() != stored_config.fingerprint():
        raise ValueError("The requested configuration does not match the dataset configuration.")
    for split, size in [
        ("train", stored_config.data.train_samples),
        ("test", stored_config.data.test_samples),
    ]:
        item = payload[split]
        expected = (size, stored_config.data.nx, stored_config.data.nt)
        if tuple(item["target"].shape) != expected or tuple(item["xi"].shape) != expected:
            raise ValueError(f"Unexpected {split} array dimensions.")
        if tuple(item["u0"].shape) != expected[:2]:
            raise ValueError(f"Unexpected {split} initial-condition dimensions.")
        if not all(
            torch.isfinite(item[key]).all().item() for key in ("u0", "xi", "target", "coefficients")
        ):
            raise ValueError(f"Nonfinite values in the {split} dataset.")
    return payload, stored_config


def dataset_source(path):
    return {"path": str(Path(path).resolve()), "sha256": sha256(path)}
